// IsReadOnlyCommand reports whether ISC classifies the exact command as read.
// Unclassified commands return false, including commands supplied by custom hooks.
func IsReadOnlyCommand(command string) bool {
	return commandAccessPolicy[command] == accessRead
}

// IsKnownCommand reports whether a command has a reviewed access classification.
// Live discovery establishes availability, never permission for unknown commands.
func IsKnownCommand(command string) bool {
	_, ok := commandAccessPolicy[command]
	return ok
}
